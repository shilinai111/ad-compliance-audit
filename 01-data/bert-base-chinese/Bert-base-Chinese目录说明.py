'''
config.json (649 字节) —— 模型“骨架”（结构蓝图）

作用：这是一个轻量级的配置文件。它定义了模型的规格，即所有超参数，比如：hidden_size: 768（隐藏层维度）、
num_hidden_layers: 12（Transformer 层数）、num_attention_heads: 12（注意力头数）、
vocab_size: 21128（词汇表大小）等。

加载模型时，程序会第一时间读取这个文件，根据里面的数字搭建起一个空的模型计算图。
但此时模型参数全是初始化的，无法完成任务。


configuration.json (42 字节) —— 源信息配置
作用：一个极小的辅助文件，用于记录模型来源（如 "from": "transformers"），
方便平台内部进行版本管理和索引，对开发者直接使用影响不大。



model.safetensors (411 MB) —— 模型“血肉”（预训练权重）

模型在海量的原始训练数据上，得到的权重参数。相当于模型在该数据上学到的所有知识和经验规律的浓缩。
加载了训练权重，则模型可以表现出强大的工作性能，称为学霸。


文本预处理“必备工具” (4个文件)这些文件负责把人类语言“翻译”成模型能看懂的数字。

vocab.txt (130 KB) —— 词汇表（字典）
作用：这是一个纯文本文件，里面列出了模型能识别的所有中文汉字、英文、标点和特殊符号（总共约 2.1 万个）。
它的顺序就是模型给每个字分配的“身份证号（ID）”。
加载时，分词器（Tokenizer）会加载它，用来把“我爱你”拆成 [我, 爱, 你]，
再查表转成 [2769, 4263, 2768] 这样的索引。


tokenizer.json (268 KB) —— 分词器主配置
作用：这是分词器的核心执行逻辑文件。它包含了完整的分词算法规则和 "词汇表" 的数据结构，
负责实现从“原始文本”到“Token 列表”的全过程。它比 vocab.txt 功能更强大，是 Python 代码实际高频调用的文件。



tokenizer_config.json (32 字节) —— 分词器行为配置
作用：指定分词器在工作时的一些具体行为，比如“最大的输入长度是多少”、“是否添加特殊标记 [CLS] 和 [SEP]”等。


'''






